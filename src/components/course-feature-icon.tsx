const REGISTRY = new Map(
  FEATURE_ICON_CHOICES.map((choice) => [choice.name, ICONS[choice.name]]),
);

/** The icon stored against a name, or the fallback tick when it is unknown. */
export function getFeatureIcon(name: string): IconComponent {
  return REGISTRY.get(name) ?? ICONS[DEFAULT_FEATURE_ICON];
}

/** Draws a feature's icon, quietly falling back to a tick. */
export function CourseFeatureIcon({
  name,
  className,
}: {
  readonly name: string;
  readonly className?: string;
}) {
  const Icon = getFeatureIcon(name);
  return <Icon className={cn("size-5", className)} />;
}
